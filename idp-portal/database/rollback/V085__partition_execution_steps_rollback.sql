        RAISE_APPLICATION_ERROR(-20011,
            'ROLLBACK COUNT MISMATCH: original=' || v_orig || ', restored=' || v_new);
    END IF;
    DBMS_OUTPUT.PUT_LINE('Rollback count validated: ' || v_new || ' rows');
END;
