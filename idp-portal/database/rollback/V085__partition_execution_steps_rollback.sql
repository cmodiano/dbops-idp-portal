-- Étape C.4 : Valider COUNT avant renommage
DECLARE
    v_orig NUMBER;
    v_new  NUMBER;
BEGIN
    SELECT ROW_COUNT INTO v_orig FROM EXEC_STEPS_ROLLBACK_CHECK;
