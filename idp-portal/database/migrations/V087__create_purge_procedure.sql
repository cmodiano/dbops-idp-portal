-- ============================================================
-- PHASE 1 : Créer la table de log de maintenance IDP_MAINTENANCE_LOG
-- (idempotente : ignorée si la table existe déjà)
-- ============================================================
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'IDP_MAINTENANCE_LOG';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE IDP_MAINTENANCE_LOG (
                ID             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT PK_IDP_MAINTENANCE_LOG PRIMARY KEY,
                EXECUTED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
                TABLE_NAME     VARCHAR2(64)  NOT NULL,
                PARTITION_NAME VARCHAR2(64)  NOT NULL,
                ACTION         VARCHAR2(32)  NOT NULL,
                STATUS         VARCHAR2(16)  NOT NULL,
                DRY_RUN        NUMBER(1)     DEFAULT 1 NOT NULL,
                NOTES          VARCHAR2(500)
            )';
        EXECUTE IMMEDIATE 'CREATE INDEX IDX_MAINT_LOG_EXECUTED_AT ON IDP_MAINTENANCE_LOG(EXECUTED_AT)';
        DBMS_OUTPUT.PUT_LINE('IDP_MAINTENANCE_LOG and IDX_MAINT_LOG_EXECUTED_AT created.');
    ELSE
        DBMS_OUTPUT.PUT_LINE('IDP_MAINTENANCE_LOG already exists — skipping creation (idempotent).');
    END IF;
END;
