    -- ===========================================================
    -- Politique de rétention par défaut (en mois)
    -- Modifiable via les paramètres des procédures publiques.
    -- ===========================================================
    gc_retention_executions  CONSTANT NUMBER := 24;  -- EXECUTIONS : 24 mois
    gc_retention_audit_log   CONSTANT NUMBER := 12;  -- AUDIT_LOG  : 12 mois (SOC1/NFR8)

    -- ===========================================================
