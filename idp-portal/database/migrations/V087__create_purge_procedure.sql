    -- ===========================================================
    PROCEDURE purge_executions(
        p_retention_months  IN NUMBER  DEFAULT 24,
        p_dry_run           IN NUMBER  DEFAULT 1
    );

    -- ===========================================================
    -- Procédure ciblée : purge AUDIT_LOG uniquement
    -- ===========================================================
    -- ⚠️  Désactivée par défaut (p_dry_run=1) — conformité SOC1/NFR8
