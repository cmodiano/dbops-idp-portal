-- V087: Procédure de purge et politique de rétention — PKG_IDP_MAINTENANCE
-- Story 40.5 - Epic 40: Partitionnement et rétention tables performance
-- Installe : TABLE IDP_MAINTENANCE_LOG + PACKAGE PKG_IDP_MAINTENANCE
-- Rollback: see database/rollback/V087__create_purge_procedure_rollback.sql
--
-- TABLES CIBLES :
--   EXECUTIONS          — partitionnée CREATED_AT Range INTERVAL (V084), rétention 24 mois
--   EXECUTION_STEPS     — Reference Partitioning sur FK EXECUTION_ID→EXECUTIONS (V085)
--                         → partitions cascadent automatiquement avec EXECUTIONS
--   AUDIT_LOG           — partitionnée TIMESTAMP Range INTERVAL (V086), rétention 12 mois
--                         ⚠️ SOC1/NFR8 : purge AUDIT_LOG désactivée par défaut (p_dry_run=1)
--
-- ORDRE DE PURGE (EXECUTIONS) :
--   1. UPDATE EXECUTIONS SET PARENT_EXECUTION_ID = NULL WHERE ... (pré-requis FK auto-ref)
--   2. DELETE FROM EXECUTION_TARGETS WHERE ... (pré-requis FK classique)
--   3. ALTER TABLE EXECUTIONS DROP PARTITION p_name UPDATE GLOBAL INDEXES
--      → EXECUTION_STEPS cascade automatiquement (Reference Partitioning)
--
-- DÉPENDANCES :
--   - EXECUTIONS partitionnée (V084) — colonne CREATED_AT comme clé de partition
--   - EXECUTION_STEPS Reference Partitioned (V085) — cascade automatique
--   - AUDIT_LOG partitionnée (V086) — colonne TIMESTAMP comme clé de partition
--   - EXECUTION_TARGETS non-partitionné — FK EXECUTION_ID → EXECUTIONS.ID (classique)
--   - FK_EXECUTIONS_PARENT : DEFERRABLE INITIALLY DEFERRED (V084 Phase 6)

-- ============================================================
-- PHASE 0 : Vérification des préconditions (idempotence)
-- ============================================================
-- Ce script est idempotent : il peut être re-exécuté sans erreur.
-- - Si les deux objets existent déjà → installation complète détectée, message et poursuite.
-- - Si un seul des deux existe → installation partielle → erreur explicite pour guide DBA.
-- - Si aucun n'existe → installation fraîche.
DECLARE
    v_pkg_exists   NUMBER;
    v_table_exists NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_pkg_exists
    FROM USER_OBJECTS
    WHERE OBJECT_NAME = 'PKG_IDP_MAINTENANCE'
      AND OBJECT_TYPE IN ('PACKAGE', 'PACKAGE BODY');

    SELECT COUNT(*) INTO v_table_exists
    FROM USER_TABLES
    WHERE TABLE_NAME = 'IDP_MAINTENANCE_LOG';

    IF v_pkg_exists > 0 AND v_table_exists > 0 THEN
        DBMS_OUTPUT.PUT_LINE(
            'V087: PKG_IDP_MAINTENANCE and IDP_MAINTENANCE_LOG already exist — '
            || 'running in idempotent mode (CREATE OR REPLACE for package, skip for table).');
    ELSIF v_pkg_exists > 0 AND v_table_exists = 0 THEN
        RAISE_APPLICATION_ERROR(-20001,
            'V087 partial installation: PKG_IDP_MAINTENANCE exists but IDP_MAINTENANCE_LOG is missing. '
            || 'Clean up manually: DROP PACKAGE PKG_IDP_MAINTENANCE');
    ELSIF v_pkg_exists = 0 AND v_table_exists > 0 THEN
        RAISE_APPLICATION_ERROR(-20002,
            'V087 partial installation: IDP_MAINTENANCE_LOG exists but PKG_IDP_MAINTENANCE is missing. '
            || 'Clean up manually: DROP TABLE IDP_MAINTENANCE_LOG PURGE');
    ELSE
        DBMS_OUTPUT.PUT_LINE('V087 preconditions OK — clean installation starting.');
    END IF;
END;
