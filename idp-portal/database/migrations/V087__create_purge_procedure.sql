    -- p_retention_audit_log  : Rétention AUDIT_LOG en mois (défaut 12)
    -- p_dry_run              : 1 = simulation (log sans DROP), 0 = exécution réelle
    --                          DÉFAUT = 1 pour éviter toute purge accidentelle
    -- ⚠️  AUDIT_LOG : valider conformité SOC1/NFR8 avant d'activer p_dry_run=0
    PROCEDURE purge_old_partitions(
        p_retention_executions  IN NUMBER  DEFAULT 24,
        p_retention_audit_log   IN NUMBER  DEFAULT 12,
        p_dry_run               IN NUMBER  DEFAULT 1
