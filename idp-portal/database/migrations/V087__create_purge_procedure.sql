-- ============================================================
-- PHASE 4 : Valider l'installation
-- ============================================================
DECLARE
    v_pkg_spec_count   NUMBER;
    v_pkg_body_count   NUMBER;
    v_table_count      NUMBER;
    v_index_count      NUMBER;
BEGIN
    -- Vérifier que le package spec est compilé et valide
    SELECT COUNT(*) INTO v_pkg_spec_count
    FROM USER_OBJECTS
    WHERE OBJECT_NAME = 'PKG_IDP_MAINTENANCE'
      AND OBJECT_TYPE = 'PACKAGE'
      AND STATUS = 'VALID';

    IF v_pkg_spec_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20010,
            'PKG_IDP_MAINTENANCE PACKAGE spec is missing or INVALID. Check compilation errors.');
    END IF;

    -- Vérifier que le package body est compilé et valide
    SELECT COUNT(*) INTO v_pkg_body_count
    FROM USER_OBJECTS
    WHERE OBJECT_NAME = 'PKG_IDP_MAINTENANCE'
      AND OBJECT_TYPE = 'PACKAGE BODY'
      AND STATUS = 'VALID';

    IF v_pkg_body_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20011,
            'PKG_IDP_MAINTENANCE PACKAGE BODY is missing or INVALID. Check compilation errors.');
    END IF;

    -- Vérifier que IDP_MAINTENANCE_LOG existe
    SELECT COUNT(*) INTO v_table_count
    FROM USER_TABLES WHERE TABLE_NAME = 'IDP_MAINTENANCE_LOG';

    IF v_table_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20012,
            'IDP_MAINTENANCE_LOG table is missing after V087 Phase 1.');
    END IF;

    -- Vérifier que l'index IDX_MAINT_LOG_EXECUTED_AT existe
    SELECT COUNT(*) INTO v_index_count
    FROM USER_INDEXES
    WHERE TABLE_NAME = 'IDP_MAINTENANCE_LOG'
      AND INDEX_NAME = 'IDX_MAINT_LOG_EXECUTED_AT';

    IF v_index_count = 0 THEN
        RAISE_APPLICATION_ERROR(-20013,
            'IDX_MAINT_LOG_EXECUTED_AT index is missing on IDP_MAINTENANCE_LOG.');
    END IF;

    DBMS_OUTPUT.PUT_LINE(
        'V087 installation validated successfully:'
        || ' PKG_IDP_MAINTENANCE (spec+body=VALID)'
        || ', IDP_MAINTENANCE_LOG (table+index OK)'
    );
END;
