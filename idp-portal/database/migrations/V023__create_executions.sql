-- Story 4.1 - Wizard d'execution en 3 etapes
-- Task 1.3 - Table EXECUTIONS pour stocker les executions d'actions

-- Table EXECUTIONS
CREATE TABLE EXECUTIONS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    ACTION_ID NUMBER NOT NULL,
    USER_ID NUMBER NOT NULL,
    ENVIRONMENT VARCHAR2(50) NOT NULL,
    PARAMETERS CLOB,
    STATUS VARCHAR2(20) DEFAULT 'SUBMITTED' NOT NULL,
    SERVICENOW_CHANGE_ID VARCHAR2(100),
    STARTED_AT TIMESTAMP WITH TIME ZONE,
    COMPLETED_AT TIMESTAMP WITH TIME ZONE,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EXECUTIONS_ACTION FOREIGN KEY (ACTION_ID) REFERENCES ACTIONS_CATALOG(ID),
    CONSTRAINT FK_EXECUTIONS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID),
    CONSTRAINT CHK_EXECUTION_STATUS CHECK (STATUS IN ('SUBMITTED', 'PENDING_APPROVAL', 'RUNNING', 'COMPLETED', 'FAILED', 'CANCELLED')),
    CONSTRAINT CHK_EXECUTION_ENV CHECK (ENVIRONMENT IN ('dev', 'staging', 'prod'))
);

-- Indexes for performance (AC: status, user_id, action_id)
CREATE INDEX IDX_EXECUTIONS_STATUS ON EXECUTIONS(STATUS);
CREATE INDEX IDX_EXECUTIONS_USER_ID ON EXECUTIONS(USER_ID);
CREATE INDEX IDX_EXECUTIONS_ACTION_ID ON EXECUTIONS(ACTION_ID);
CREATE INDEX IDX_EXECUTIONS_CREATED_AT ON EXECUTIONS(CREATED_AT);

-- Comments
COMMENT ON TABLE EXECUTIONS IS 'Execution records for actions. Story 4.1 - Wizard d''execution';
COMMENT ON COLUMN EXECUTIONS.ID IS 'Primary key, auto-generated identity';
COMMENT ON COLUMN EXECUTIONS.ACTION_ID IS 'FK to ACTIONS_CATALOG - the action being executed';
COMMENT ON COLUMN EXECUTIONS.USER_ID IS 'FK to USERS - the user who initiated the execution';
COMMENT ON COLUMN EXECUTIONS.ENVIRONMENT IS 'Target environment: dev, staging, prod';
COMMENT ON COLUMN EXECUTIONS.PARAMETERS IS 'JSON parameters submitted by user, validated against action parameters_schema';
COMMENT ON COLUMN EXECUTIONS.STATUS IS 'Execution status: SUBMITTED, PENDING_APPROVAL, RUNNING, COMPLETED, FAILED, CANCELLED';
COMMENT ON COLUMN EXECUTIONS.SERVICENOW_CHANGE_ID IS 'ServiceNow change ticket ID if change management required';
COMMENT ON COLUMN EXECUTIONS.STARTED_AT IS 'Timestamp when execution actually started running';
COMMENT ON COLUMN EXECUTIONS.COMPLETED_AT IS 'Timestamp when execution completed (success or failure)';
COMMENT ON COLUMN EXECUTIONS.CREATED_AT IS 'Timestamp when execution was submitted';
