COMMENT ON COLUMN EXECUTION_STEPS.EXECUTION_ID IS
    'FK to EXECUTIONS.ID — partition key héritée (Reference Partitioning). V085.';
COMMENT ON COLUMN EXECUTION_STEPS.ID IS
    'Primary key, IDENTITY column. Backed by global unique index (PK_EXECUTION_STEPS). V085.';
