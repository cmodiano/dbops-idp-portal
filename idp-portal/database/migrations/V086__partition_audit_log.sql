COMMENT ON TABLE AUDIT_LOG IS
    'Append-only audit log. Range INTERVAL Partitioned by TIMESTAMP (monthly). Story 40.4. SOC1/NFR8: immutable via trigger TRG_AUDIT_LOG_IMMUTABLE.';
COMMENT ON COLUMN AUDIT_LOG.TIMESTAMP IS
    'Partition key (Range INTERVAL monthly). Auto-set to SYSTIMESTAMP on INSERT. V086.';
COMMENT ON COLUMN AUDIT_LOG.ID IS
    'Primary key, IDENTITY column (BY DEFAULT ON NULL after V086 migration). Backed by global unique index PK_AUDIT_LOG.';
COMMENT ON COLUMN AUDIT_LOG.CORRELATION_ID IS
    'Optional correlation ID for cross-request tracing. Indexed via IDX_AUDIT_LOG_CORRELATION (GLOBAL) for queries without date filter.';
