-- V043: Add surrogate ID to USER_FAVORITES for Django ORM compatibility
-- Original table (V021) used composite PK (USER_ID, ACTION_ID). Django expects a single-column PK.

ALTER TABLE USER_FAVORITES ADD (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
);

UPDATE USER_FAVORITES SET ID = DEFAULT WHERE ID IS NULL;

ALTER TABLE USER_FAVORITES DROP CONSTRAINT PK_USER_FAVORITES;
ALTER TABLE USER_FAVORITES ADD CONSTRAINT PK_USER_FAVORITES PRIMARY KEY (ID);
ALTER TABLE USER_FAVORITES ADD CONSTRAINT UK_USER_FAVORITES_USER_ACTION UNIQUE (USER_ID, ACTION_ID);
