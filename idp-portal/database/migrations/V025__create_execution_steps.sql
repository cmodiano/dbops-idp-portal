-- V025: Create EXECUTION_STEPS table
-- Story 4.3 - Moteur d'execution et facade API
-- Task 1.2 - Table EXECUTION_STEPS pour tracer les etapes d'une execution

-- Table EXECUTION_STEPS
CREATE TABLE EXECUTION_STEPS (
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    EXECUTION_ID NUMBER NOT NULL,
    STEP_ORDER NUMBER NOT NULL,
    STEP_NAME VARCHAR2(255) NOT NULL,
    STEP_TYPE VARCHAR2(50) NOT NULL,
    STATUS VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    STARTED_AT TIMESTAMP WITH TIME ZONE,
    COMPLETED_AT TIMESTAMP WITH TIME ZONE,
    OUTPUT CLOB,
    PLATFORM_JOB_ID VARCHAR2(255),
    ERROR_MESSAGE CLOB,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_EXEC_STEPS_EXECUTION FOREIGN KEY (EXECUTION_ID) REFERENCES EXECUTIONS(ID) ON DELETE CASCADE,
    CONSTRAINT CHK_STEP_STATUS CHECK (STATUS IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED', 'SKIPPED')),
    CONSTRAINT CHK_STEP_TYPE CHECK (STEP_TYPE IN ('vault', 'servicenow', 'platform', 'prerequisite', 'verification')),
    CONSTRAINT UQ_EXEC_STEP_ORDER UNIQUE (EXECUTION_ID, STEP_ORDER)
);

-- Indexes for performance (AC: execution_id + step_order for ordered retrieval)
CREATE INDEX IDX_EXEC_STEPS_EXECUTION_ID ON EXECUTION_STEPS(EXECUTION_ID);
CREATE INDEX IDX_EXEC_STEPS_STATUS ON EXECUTION_STEPS(STATUS);

-- Comments
COMMENT ON TABLE EXECUTION_STEPS IS 'Execution step records. Story 4.3 - Moteur d''execution';
COMMENT ON COLUMN EXECUTION_STEPS.ID IS 'Primary key, auto-generated identity';
COMMENT ON COLUMN EXECUTION_STEPS.EXECUTION_ID IS 'FK to EXECUTIONS - the parent execution';
COMMENT ON COLUMN EXECUTION_STEPS.STEP_ORDER IS 'Order of step in execution sequence (1-based)';
COMMENT ON COLUMN EXECUTION_STEPS.STEP_NAME IS 'Display name of the step (e.g., Recuperation secrets Vault)';
COMMENT ON COLUMN EXECUTION_STEPS.STEP_TYPE IS 'Step type: vault, servicenow, platform, prerequisite, verification';
COMMENT ON COLUMN EXECUTION_STEPS.STATUS IS 'Step status: PENDING, RUNNING, COMPLETED, FAILED, SKIPPED';
COMMENT ON COLUMN EXECUTION_STEPS.STARTED_AT IS 'Timestamp when step started running';
COMMENT ON COLUMN EXECUTION_STEPS.COMPLETED_AT IS 'Timestamp when step completed';
COMMENT ON COLUMN EXECUTION_STEPS.OUTPUT IS 'JSON output from step execution';
COMMENT ON COLUMN EXECUTION_STEPS.PLATFORM_JOB_ID IS 'External job ID from platform (AAP, Terraform, etc.)';
COMMENT ON COLUMN EXECUTION_STEPS.ERROR_MESSAGE IS 'Error details if step failed';
COMMENT ON COLUMN EXECUTION_STEPS.CREATED_AT IS 'Timestamp when step record was created';
